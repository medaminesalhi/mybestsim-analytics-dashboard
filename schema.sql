-- 1. Fournisseurs
CREATE TABLE IF NOT EXISTS providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Registre des datasets
CREATE TABLE IF NOT EXISTS datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL UNIQUE,
    provider_id BIGINT NOT NULL REFERENCES providers(id),
    expected BOOLEAN NOT NULL DEFAULT TRUE,

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'uploaded', 'processing',
            'active', 'disabled', 'error'
        )),

    storage_path TEXT,
    last_checksum CHAR(64),
    last_imported_at TIMESTAMPTZ,
    last_row_count INTEGER,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Journal des executions du pipeline
CREATE TABLE IF NOT EXISTS import_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES datasets(id),

    checksum CHAR(64) NOT NULL,

    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN (
            'running', 'succeeded', 'failed', 'skipped'
        )),

    total_rows INTEGER NOT NULL DEFAULT 0,
    inserted_rows INTEGER NOT NULL DEFAULT 0,
    updated_rows INTEGER NOT NULL DEFAULT 0,
    unchanged_rows INTEGER NOT NULL DEFAULT 0,
    rejected_rows INTEGER NOT NULL DEFAULT 0,

    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    error_message TEXT
);

-- 4. Catalogue courant des produits
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    dataset_id BIGINT NOT NULL REFERENCES datasets(id),
    sku TEXT NOT NULL,
    product_name TEXT NOT NULL,

    country_code TEXT,
    country_name TEXT,

    data_gb NUMERIC(12,3)
        CHECK (data_gb IS NULL OR data_gb >= 0),
    data_display TEXT,

    validity_days INTEGER
        CHECK (validity_days IS NULL OR validity_days > 0),

    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    currency VARCHAR(3) NOT NULL,

    network TEXT,
    top_up BOOLEAN,

    source_hash CHAR(64) NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (dataset_id, sku)
);

-- 5. Historique des prix observes a chaque import
CREATE TABLE IF NOT EXISTS product_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL
        REFERENCES products(id) ON DELETE CASCADE,

    import_run_id BIGINT NOT NULL
        REFERENCES import_runs(id),

    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    currency VARCHAR(3) NOT NULL,

    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (product_id, import_run_id)
);

-- 6. Lignes rejetees pendant la validation
CREATE TABLE IF NOT EXISTS rejected_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    import_run_id BIGINT NOT NULL
        REFERENCES import_runs(id),

    source_row_number INTEGER,
    row_data JSONB NOT NULL,
    error_message TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =====================================================
-- INDEX POUR LES RECHERCHES ET LES FILTRES
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_products_price
    ON products(price);

CREATE INDEX IF NOT EXISTS idx_products_country
    ON products(country_code);

CREATE INDEX IF NOT EXISTS idx_products_network
    ON products(network);

CREATE INDEX IF NOT EXISTS idx_products_dataset_active
    ON products(dataset_id, is_active);

CREATE INDEX IF NOT EXISTS idx_import_runs_dataset_date
    ON import_runs(dataset_id, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_price_history_product_date
    ON product_price_history(product_id, captured_at DESC);

-- =====================================================
-- VUE ANALYTIQUE PRINCIPALE
-- =====================================================

CREATE OR REPLACE VIEW analytics_kpis AS
SELECT
    COUNT(*) AS total_products,

    COUNT(*) FILTER (
        WHERE p.price > 100
    ) AS products_over_100,

    MIN(p.price) AS min_price,
    MAX(p.price) AS max_price,

    ROUND(AVG(p.price), 2) AS avg_price,

    ROUND(AVG(p.data_gb), 2)
        AS avg_data_gb_numeric_plans,

    COUNT(*) FILTER (
        WHERE LOWER(COALESCE(p.data_display, ''))
              LIKE '%illimité%'
    ) AS unlimited_products,

    COUNT(DISTINCT p.dataset_id) AS active_datasets

FROM products p
JOIN datasets d ON d.id = p.dataset_id

WHERE d.status = 'active'
  AND p.is_active = TRUE;

-- =====================================================
-- VUE DE REPARTITION PAR FOURNISSEUR
-- =====================================================

CREATE OR REPLACE VIEW provider_distribution AS
SELECT
    pr.name AS provider,
    COUNT(p.id) AS product_count,
    ROUND(AVG(p.price), 2) AS avg_price,
    MIN(p.price) AS min_price,
    MAX(p.price) AS max_price,

    COUNT(*) FILTER (
        WHERE p.price > 100
    ) AS products_over_100

FROM products p
JOIN datasets d ON d.id = p.dataset_id
JOIN providers pr ON pr.id = d.provider_id

WHERE d.status = 'active'
  AND p.is_active = TRUE

GROUP BY pr.id, pr.name;
